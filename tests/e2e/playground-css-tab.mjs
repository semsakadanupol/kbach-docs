// The generated CSS as an editor tab (kbach.css), and scrolling past the last line.
import { chromium } from 'playwright';
import { cdnPage } from './example-link.js';
let failures = 0;
const check = (ok, msg) => {
  console.log((ok ? 'OK   ' : 'FAIL ') + msg);
  if (!ok) failures++;
};
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1920, height: 1000 }, permissions: ['clipboard-read', 'clipboard-write'] });
const p = await ctx.newPage();
const errors = [];
p.on('pageerror', (e) => !/about:srcdoc/.test(e.stack || '') && errors.push(e.message));
await p.goto('http://localhost:5176/playground', { waitUntil: 'networkidle' });
await p.evaluate(() => localStorage.clear());
await p.reload({ waitUntil: 'networkidle' });
await p.waitForTimeout(1200);

const tab = (name) => p.locator('[role="tablist"][aria-label="Files"] [role="tab"]', { hasText: name });
const shown = '.cm-editor:visible';
// CodeMirror only draws the lines in view: read the whole document through its view
const docText = () => p.$eval(shown + ' .cm-content', (el) => el.cmView?.view?.state.doc.toString() ?? [...el.querySelectorAll('.cm-line')].map((l) => l.textContent).join('\n'));
const setFiles = async (html, script) => {
  await tab('script').click();
  await p.fill(shown + ' .cm-content', script);
  await tab('index.html').click();
  // a whole page, as HTML mode has one: it loads kbach.config.js (the landing page's, darkMode: 'class'), then the CDN script
  await p.fill(shown + ' .cm-content', cdnPage(html));
  await p.waitForTimeout(900);
};

check(!(await p.$('section[aria-label="Output"] button:has-text("CSS")')), 'the output has no CSS tab any more (Preview and Console)');
check((await tab('kbach.css').count()) === 1, 'the editor has a kbach.css file tab');

await setFiles('<div class="p-4 md:flex hover:bg-sky-7">x</div>', '');
await tab('kbach.css').click();
await p.waitForTimeout(300);
// the whole file, through Copy (the editor only draws the lines in view)
const cssFile = async () => {
  await p.click('section[aria-label="Code"] button[aria-label="Copy code"]');
  await p.waitForTimeout(200);
  // (the Windows clipboard hands text back with CRLF)
  return (await p.evaluate(() => navigator.clipboard.readText())).replace(/\r\n/g, '\n');
};
let css = await cssFile();
// the file the build plugin writes: markers, header, reset, :root, then the rules using its variables
check(
  css.startsWith('/* kbach:start */\n/* Generated by Kbach — do not edit */') &&
    css.includes(':root {\n  --kb-dark-mode: class;') &&
    css.includes('--spacing-4: 16px;') &&
    css.includes('.p-4 {\n  padding: var(--spacing-4);\n}'),
  'kbach.css is the file the build plugin writes: :root variables, and rules laid out a declaration per line ',
);
check(css.includes('@media (min-width: 768px) {\n  .md\\:flex {\n    display: flex;\n  }\n}'), 'with @media blocks nested and indented');
check((await p.$$eval(shown + ' .cm-content span', (s) => s.length)) > 5, 'with CSS syntax colors');

// read-only
await p.click(shown + ' .cm-content');
await p.keyboard.press('Control+End');
await p.keyboard.type('hello');
await p.keyboard.press('Shift+Alt+F');
await p.waitForTimeout(400);
check((await docText()) === css, 'typing (and Format) can\'t change it');
const bar = await p.locator('section[aria-label="Code"] > div:last-of-type').first().innerText();
check(/CSS · \d+ rules · read-only/.test(bar) && !bar.includes('Format'), 'the status bar counts the rules, says read-only, and has no Format button: ' + bar.replace(/\s+/g, ' '));

// live, while it's open
await tab('index.html').click();
await p.click(shown + ' .cm-content');
await p.keyboard.press('Control+A');
await p.keyboard.type('<div class="p-4 rounded-lg">x</div>', { delay: 5 });
await p.waitForTimeout(700);
await tab('kbach.css').click();
await p.waitForTimeout(200);
css = await cssFile();
check(css.includes('.rounded-lg {\n  border-radius: 0.5rem;\n}') && !css.includes('md\\:flex'), 'it follows the HTML as you edit');
check(css.trimEnd().endsWith('/* kbach:end */'), 'Copy copies the whole file');
check((await p.$('section[aria-label="Output"] button:has-text("rules")')) === null, 'the preview has no rules link under it any more (the tab is the one place)');

// scroll past the last line, as VS Code does
await tab('index.html').click();
await p.fill(shown + ' .cm-content', Array.from({ length: 60 }, (_, i) => `<p class="p-1">Line ${i + 1}</p>`).join('\n'));
await p.waitForTimeout(400);
const past = await p.$eval(shown + ' .cm-scroller', (s) => {
  s.scrollTop = s.scrollHeight;
  const lines = s.querySelectorAll('.cm-line');
  const last = lines[lines.length - 1].getBoundingClientRect();
  const top = s.getBoundingClientRect().top;
  return { lastLineFromTop: Math.round(last.top - top), height: s.clientHeight, lineHeight: Math.round(last.height) };
});
check(past.lastLineFromTop < past.lineHeight * 3, 'scrolled to the end, the last line can sit at the top of the editor (' + JSON.stringify(past) + ')');
// a file shorter than the editor: its last line can still be scrolled up to the top
await p.fill(shown + ' .cm-content', Array.from({ length: 6 }, (_, i) => '<p>Line ' + (i + 1) + '</p>').join('\n'));
await p.waitForTimeout(300);
const short = await p.$eval(shown + ' .cm-scroller', (s) => {
  s.scrollTop = s.scrollHeight;
  const lines = s.querySelectorAll('.cm-line');
  const last = lines[lines.length - 1].getBoundingClientRect();
  return { room: s.scrollHeight - s.clientHeight, lastLineFromTop: Math.round(last.top - s.getBoundingClientRect().top), lineHeight: Math.round(last.height) };
});
check(short.room > 0 && short.lastLineFromTop < short.lineHeight * 3, 'a short file (6 lines) can scroll its last line up to the top too (' + JSON.stringify(short) + ')');

check(errors.length === 0, 'no page errors ' + errors.join(' | '));
await b.close();
console.log(failures ? failures + ' FAILED' : 'ALL PASSED');
process.exit(failures ? 1 : 0);
